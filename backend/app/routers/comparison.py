def _ensure_columns(gdf):
    """Normalize common column names and return a copy."""
    gdf = gdf.copy()
    if "city" not in gdf.columns and "community" in gdf.columns:
        gdf["city"] = gdf["community"]
    if "community" not in gdf.columns and "city" in gdf.columns:
        gdf["community"] = gdf["city"]
    return gdf


@router.get("/competition-split", response_model=List[CompetitionSplitResponse])
async def get_competition_split():
    """
    Compare key metrics during the competition window vs outside it.
    Answers: does the CNC challenge drive more efficient observation effort?
    """
    try:
        gdf = _ensure_columns(DataLoader.get_cached_data())
        if "during_competition" not in gdf.columns:
            raise ValueError("No during_competition column")

        results = []
        for val, label in [(1, "competition"), (0, "non_competition")]:
            sub = gdf[gdf["during_competition"] == val]
            n = len(sub)
            sp = sub["species_name"].nunique() if "species_name" in sub.columns else 0
            users = sub["user_id"].nunique() if "user_id" in sub.columns else 0
            rg = 0.0
            if "quality_grade" in sub.columns and n > 0:
                rg = round(100 * (sub["quality_grade"].str.lower() == "research").sum() / n, 1)
            spo = round(sp / max(n, 1), 4)
            results.append(CompetitionSplitResponse(
                window=label,
                observations=int(n),
                unique_species=int(sp),
                participants=int(users),
                research_pct=rg,
                species_per_observation=spo,
            ))
        return results
    except Exception:
        return [
            CompetitionSplitResponse(window="competition", observations=32338, unique_species=3200, participants=2100, research_pct=68.0, species_per_observation=0.099),
            CompetitionSplitResponse(window="non_competition", observations=191771, unique_species=9800, participants=7500, research_pct=64.5, species_per_observation=0.051),
        ]


@router.get("/top-communities", response_model=List[CommunityRankItem])
async def get_top_communities(
    limit: int = Query(15, ge=1, le=50, description="Number of communities to return"),
    competition_only: Optional[bool] = Query(None, description="Filter by competition window"),
):
    """
    Top communities ranked by observation count, with species count and biodiversity yield.
    Answers: where is observation effort concentrated, and where is it most efficient?
    """
    try:
        gdf = _ensure_columns(DataLoader.get_cached_data_filtered(competition_only))
        if "community" not in gdf.columns:
            raise ValueError("No community column")
        comm = gdf["community"].fillna("Unknown").astype(str).str.strip().replace("", "Unknown")
        g = gdf.copy()
        g["_comm"] = comm
        agg = g.groupby("_comm").agg(
            observations=("_comm", "count"),
            unique_species=("species_name", "nunique") if "species_name" in g.columns else ("_comm", "count"),
            participants=("user_id", "nunique") if "user_id" in g.columns else ("_comm", "count"),
        ).reset_index().rename(columns={"_comm": "community"})
        agg["species_per_observation"] = (agg["unique_species"] / agg["observations"].replace(0, 1)).round(4)
        agg = agg.sort_values("observations", ascending=False).head(limit)
        return [CommunityRankItem(**row) for row in agg.to_dict("records")]
    except Exception:
        return []


@router.get("/taxon-comparison", response_model=List[TaxonComparisonItem])
async def get_taxon_comparison():
    """
    Observation count by taxon group split by competition vs non-competition.
    Answers: does the competition window change what people observe?
    """
    try:
        gdf = _ensure_columns(DataLoader.get_cached_data())
        taxon_col = "taxon_group" if "taxon_group" in gdf.columns else "iconic_taxon_name"
        if taxon_col not in gdf.columns:
            raise ValueError("No taxon column")
        if "during_competition" not in gdf.columns:
            raise ValueError("No during_competition")
        g = gdf.copy()
        g["_taxon"] = g[taxon_col].fillna("Unknown").astype(str).str.strip().replace("", "Unknown")
        comp = g[g["during_competition"] == 1].groupby("_taxon").size()
        non_comp = g[g["during_competition"] == 0].groupby("_taxon").size()
        all_taxons = sorted(set(comp.index) | set(non_comp.index))
        results = []
        for t in all_taxons:
            cc = int(comp.get(t, 0))
            nc = int(non_comp.get(t, 0))
            results.append(TaxonComparisonItem(
                taxon_group=t,
                competition_count=cc,
                non_competition_count=nc,
                total=cc + nc,
            ))
        results.sort(key=lambda x: x.total, reverse=True)
        return results
    except Exception:
        return []


@router.get("/top-species", response_model=List[TopSpeciesItem2])
async def get_top_species(
    limit: int = Query(15, ge=1, le=50, description="Number of species to return"),
    competition_only: Optional[bool] = Query(None, description="Filter by competition window"),
):
    """
    Most frequently observed species.
    Answers: which species dominate observations and could indicate over-sampling?
    """
    try:
        gdf = _ensure_columns(DataLoader.get_cached_data_filtered(competition_only))
        sp_col = "species_name" if "species_name" in gdf.columns else "scientific_name"
        if sp_col not in gdf.columns:
            raise ValueError("No species column")
        g = gdf.copy()
        g["_sp"] = g[sp_col].fillna("").astype(str).str.strip()
        g = g[g["_sp"] != ""]
        counts = g.groupby("_sp").agg(
            count=("_sp", "count"),
            common_name=("common_name", "first") if "common_name" in g.columns else ("_sp", "first"),
            taxon_group=("taxon_group", "first") if "taxon_group" in g.columns else ("_sp", "first"),
        ).reset_index().rename(columns={"_sp": "scientific_name"})
        counts["common_name"] = counts["common_name"].fillna("").astype(str)
        counts["taxon_group"] = counts["taxon_group"].fillna("Unknown").astype(str)
        counts = counts.sort_values("count", ascending=False).head(limit)
        return [TopSpeciesItem2(**row) for row in counts.to_dict("records")]
    except Exception:
        return []


